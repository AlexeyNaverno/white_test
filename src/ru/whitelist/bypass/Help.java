    /** Диалог справки: заголовок + прокручиваемый текст. */
    public static void show(Context c, String title, String text) {
        ScrollView scroll = new ScrollView(c);
        TextView tv = new TextView(c);
        int pad = (int) (16 * c.getResources().getDisplayMetrics().density);
        tv.setPadding(pad, pad, pad, pad);
        tv.setText(text);
        tv.setTextSize(14);
        tv.setTextColor(Ui.TEXT);
        tv.setLineSpacing(0f, 1.25f);
        tv.setMovementMethod(LinkMovementMethod.getInstance());
        scroll.addView(tv);
        new AlertDialog.Builder(c)
                .setTitle(title)
                .setView(scroll)
                .setPositiveButton("Понятно", null)
                .show();
    }

    /** Тот же диалог, но с готовым View (используется для длинных текстов из assets). */
    public static void showView(Context c, String title, View content) {
        new AlertDialog.Builder(c)
                .setTitle(title)
                .setView(content)
                .setPositiveButton("Понятно", null)
                .show();
    }
